#!/usr/bin/env python3
"""Build, flash, capture and validate isolated ESP32 path-planner profiles.

Requires Python package pyserial and an ESP-IDF environment in the caller shell.
It never invents results: a missing completion marker or malformed/conflicting CSV
row terminates the run with a non-zero exit status.
"""
import argparse, csv, datetime as dt, json, math, os, re, shutil, statistics, subprocess, sys, time
from collections import defaultdict
from pathlib import Path

try:
    import serial
except ImportError as exc:
    raise SystemExit("pyserial is required: python3 -m pip install pyserial") from exc

PLANNERS = ("AStar", "JPS", "DStarLite")
SCENARIOS = ("initial_50x50_density10", "initial_100x100_density20", "initial_500x500_density20",
             "dynamic_50x50_density10", "dynamic_100x100_density20", "dynamic_500x500_density30")
FIELDS = ['experiment_id','planner','phase','grid_width','grid_height','density','update_mode','map_id','seed',
          'repetition','warmup','status','success','path_cost','expanded_nodes','elapsed_us','free_heap_before',
          'free_heap_after','since_boot_minimum_free_heap_before','since_boot_minimum_free_heap_after',
          'failed_alloc_bytes','failure_stage','failure_reason','update_x','update_y','psram_enabled',
          'cpu_frequency_mhz','esp_idf_version','firmware_git_commit']

def now(): return dt.datetime.now(dt.timezone.utc).isoformat()
def git_commit(project):
    try: return subprocess.check_output(['git','-C',str(project),'rev-parse','HEAD'], text=True, stderr=subprocess.DEVNULL).strip()
    except subprocess.CalledProcessError: return 'unavailable'
def cpp_string(s): return s.replace('\\','\\\\').replace('"','\\"')
def write_profile(path, planner, scenario, first, count, warmups, reps, experiment, commit):
    path.write_text('#pragma once\n// Generated by tools/run_esp32_matrix.py; do not edit during a run.\n'
                    f'#define BENCHMARK_PLANNER "{cpp_string(planner)}"\n#define BENCHMARK_SCENARIO "{cpp_string(scenario)}"\n'
                    f'#define BENCHMARK_INSTANCE_START {first}\n#define BENCHMARK_INSTANCE_COUNT {count}\n'
                    f'#define BENCHMARK_WARMUP_COUNT {warmups}\n#define BENCHMARK_MEASURE_COUNT {reps}\n'
                    f'#define BENCHMARK_EXPERIMENT_ID "{cpp_string(experiment)}"\n'
                    f'#define BENCHMARK_FIRMWARE_GIT_COMMIT "{cpp_string(commit)}"\n')
def command(cmd, cwd): subprocess.run(cmd, cwd=cwd, check=True)
def extract_csv(line):
    line=re.sub(r'\x1b\[[0-?]*[ -/]*[@-~]', '', line)
    pos=line.find('csv,')
    if pos < 0: return None
    return next(csv.reader([line[pos+4:].strip()]))
def capture(device, baud, timeout, raw_path):
    deadline=time.monotonic()+timeout; lines=[]; complete=False
    with serial.Serial(device, baud, timeout=0.25) as port:
        while time.monotonic() < deadline:
            text=port.readline().decode('utf-8', errors='replace').rstrip('\r\n');
            if not text: continue
            lines.append(text)
            if ('Guru Meditation' in text or 'abort()' in text or 'abort called' in text
                    or 'Task watchdog got triggered' in text or 'task_wdt:' in text):
                raw_path.write_text('\n'.join(lines)+'\n'); raise RuntimeError('fatal firmware output: '+text)
            if text.strip() == 'planner_scenario_complete' or 'planner_scenario_complete' in text:
                complete=True; break
    raw_path.write_text('\n'.join(lines)+'\n')
    if not complete: raise RuntimeError('completion marker not seen before timeout')
    return lines
def parse_rows(lines):
    rows=[]
    for line in lines:
        values=extract_csv(line)
        if values is None: continue
        if values and values[0] == 'header': continue
        if len(values) != len(FIELDS): raise RuntimeError(f'CSV schema invalid: {len(values)} fields, expected {len(FIELDS)}: {line}')
        rows.append(dict(zip(FIELDS, values)))
    if not rows: raise RuntimeError('completion marker seen but no result CSV rows captured')
    return rows
def key(row): return (row['update_mode'],row['grid_width']+'x'+row['grid_height'],row['map_id'],row['repetition'],row['planner'],row['phase'])
def check_cost_agreement(rows):
    costs=defaultdict(dict)
    for r in rows:
        if r['status']=='OK' and r['success']=='1': costs[(r['map_id'],r['repetition'],r['phase'])][r['planner']]=r['path_cost']
    for sample, planners in costs.items():
        if len(planners)==3 and len(set(planners.values())) != 1:
            raise RuntimeError(f'path-cost disagreement for {sample}: {planners}')
def q(values, p):
    values=sorted(values); x=(len(values)-1)*p; return values[math.floor(x)]+(values[math.ceil(x)]-values[math.floor(x)])*(x-math.floor(x))
def summarize(rows, out):
    groups=defaultdict(list)
    for r in rows: groups[(r['planner'],r['update_mode'],r['grid_width'],r['grid_height'],r['density'],r['phase'])].append(r)
    fields=['planner','scenario','phase','attempted_count','completed_count','completion_rate','oom_count','other_failure_count',
            'median_elapsed_us_completed_only','q1_elapsed_us_completed_only','q3_elapsed_us_completed_only','p95_elapsed_us_completed_only',
            'median_expanded_nodes_completed_only','since_boot_minimum_free_heap','failure_stages','notes']
    with out.open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields); w.writeheader()
        for (planner, mode, width, height, density, phase), rs in sorted(groups.items()):
            formal=[r for r in rs if r['warmup']=='0']; done=[r for r in formal if r['status']=='OK' and r['success']=='1']
            elapsed=[float(r['elapsed_us']) for r in done]; expanded=[float(r['expanded_nodes']) for r in done]
            stages=sorted({r['failure_stage'] for r in formal if r['status'] not in ('OK','SKIP')})
            minimum=[int(r['since_boot_minimum_free_heap_after']) for r in formal]
            w.writerow(dict(planner=planner,scenario=f'{"dynamic" if mode != "none" else "initial"}_{width}x{height}_density{int(float(density))}',phase=phase,
                attempted_count=len(formal),completed_count=len(done),completion_rate=len(done)/len(formal) if formal else 0,
                oom_count=sum(r['status']=='OOM' for r in formal),other_failure_count=sum(r['status'] not in ('OK','OOM','SKIP') for r in formal),
                median_elapsed_us_completed_only=statistics.median(elapsed) if elapsed else '',q1_elapsed_us_completed_only=q(elapsed,.25) if elapsed else '',q3_elapsed_us_completed_only=q(elapsed,.75) if elapsed else '',p95_elapsed_us_completed_only=q(elapsed,.95) if elapsed else '',median_expanded_nodes_completed_only=statistics.median(expanded) if expanded else '',since_boot_minimum_free_heap=min(minimum) if minimum else '',failure_stages=';'.join(stages),notes='since_boot_minimum_free_heap is a global low-water mark'))
def write_outputs(output, rows, manifest):
    with (output/'esp32_raw.csv').open('w',newline='') as f: w=csv.DictWriter(f,fieldnames=FIELDS); w.writeheader(); w.writerows(rows)
    mf=['run_id','planner','scenario','start_time','end_time','firmware_commit','device','timeout','completion_marker_seen','reset_method']
    with (output/'esp32_run_manifest.csv').open('w',newline='') as f: w=csv.DictWriter(f,fieldnames=mf); w.writeheader(); w.writerows(manifest)
    failures=[r for r in rows if r['status'] not in ('OK','SKIP')]
    with (output/'esp32_failure_log.csv').open('w',newline='') as f: w=csv.DictWriter(f,fieldnames=FIELDS); w.writeheader(); w.writerows(failures)
    summarize(rows,output/'esp32_summary.csv')
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--device',required=True); ap.add_argument('--project',required=True,type=Path)
    ap.add_argument('--baud',type=int,default=115200); ap.add_argument('--timeout',type=int,default=300); ap.add_argument('--output',type=Path,default=Path('results/esp32_rerun'))
    ap.add_argument('--planner',choices=PLANNERS); ap.add_argument('--scenario',choices=SCENARIOS); ap.add_argument('--single-instance',type=int)
    ap.add_argument('--instances',type=int,default=10); ap.add_argument('--warmups',type=int,default=1); ap.add_argument('--repetitions',type=int,default=3); ap.add_argument('--smoke',action='store_true'); a=ap.parse_args()
    if shutil.which('idf.py') is None: raise SystemExit('idf.py is not on PATH; source ESP-IDF export.sh first')
    if a.single_instance is not None: a.instances=1
    if a.smoke: a.planner='AStar'; a.scenario='initial_50x50_density10'; a.instances=1; a.warmups=1; a.repetitions=1
    planners=(a.planner,) if a.planner else PLANNERS; scenarios=(a.scenario,) if a.scenario else SCENARIOS
    a.output.mkdir(parents=True,exist_ok=True); raw_dir=a.output/'raw_logs'; raw_dir.mkdir(exist_ok=True)
    profile=a.project/'main'/'benchmark_profile.h'; original=profile.read_text() if profile.exists() else None; commit=git_commit(a.project); run_id='esp32_'+dt.datetime.now().strftime('%Y%m%dT%H%M%SZ')
    all_rows=[]; manifest=[]; seen={}
    try:
      for planner in planners:
       for scenario in scenarios:
        first=a.single_instance if a.single_instance is not None else 0; exp=f'{run_id}_{planner}_{scenario}_i{first}'
        write_profile(profile,planner,scenario,first,a.instances,a.warmups,a.repetitions,exp,commit)
        start=now(); raw=raw_dir/f'{planner}__{scenario}__i{first}.log'
        try:
            command(['idf.py','build'],a.project); command(['idf.py','-p',a.device,'flash'],a.project)
            rows=parse_rows(capture(a.device,a.baud,a.timeout,raw)); complete=True
        except Exception:
            manifest.append(dict(run_id=run_id,planner=planner,scenario=scenario,start_time=start,end_time=now(),firmware_commit=commit,device=a.device,timeout=a.timeout,completion_marker_seen=0,reset_method='flash'))
            raise
        manifest.append(dict(run_id=run_id,planner=planner,scenario=scenario,start_time=start,end_time=now(),firmware_commit=commit,device=a.device,timeout=a.timeout,completion_marker_seen=int(complete),reset_method='flash'))
        for row in rows:
            k=key(row)
            if k in seen and seen[k] != row: raise RuntimeError(f'conflicting duplicate sample key: {k}')
            if k in seen: raise RuntimeError(f'duplicate sample key: {k}')
            seen[k]=row; all_rows.append(row)
    finally:
      if original is not None: profile.write_text(original)
      write_outputs(a.output,all_rows,manifest)
    check_cost_agreement(all_rows)
if __name__ == '__main__': main()